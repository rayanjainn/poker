use std::sync::Arc;
use dashmap::DashMap;
use sqlx::PgPool;
use tokio::sync::broadcast;
use uuid::Uuid;

use crate::ws::messages::ServerMessage;

pub use table::PokerTable;

/// Manages all active poker tables
#[derive(Clone)]
pub struct TableManager {
    pub tables: Arc<DashMap<Uuid, Arc<tokio::sync::Mutex<PokerTable>>>>,
    pub broadcasters: Arc<DashMap<Uuid, broadcast::Sender<ServerMessage>>>,
    pub db: PgPool,
}

impl TableManager {
    pub fn new(db: PgPool) -> Self {
        Self {
            tables: Arc::new(DashMap::new()),
            broadcasters: Arc::new(DashMap::new()),
            db,
        }
    }

    pub fn create_table(
        &self,
        table_id: Uuid,
        creator_id: Uuid,
        small_blind: i64,
        big_blind: i64,
        min_buy_in: i64,
        max_buy_in: i64,
        max_players: usize,
    ) -> broadcast::Receiver<ServerMessage> {
        let table = PokerTable::new(
            table_id,
            creator_id,
            small_blind,
            big_blind,
            min_buy_in,
            max_buy_in,
            max_players,
        );
        let (tx, rx) = broadcast::channel(256);

        self.tables.insert(table_id, Arc::new(tokio::sync::Mutex::new(table)));
        self.broadcasters.insert(table_id, tx);

        rx
    }

    pub fn get_table(&self, table_id: &Uuid) -> Option<Arc<tokio::sync::Mutex<PokerTable>>> {
        self.tables.get(table_id).map(|t| t.value().clone())
    }

    pub fn get_broadcaster(&self, table_id: &Uuid) -> Option<broadcast::Sender<ServerMessage>> {
        self.broadcasters.get(table_id).map(|b| b.value().clone())
    }

    pub fn subscribe(&self, table_id: &Uuid) -> Option<broadcast::Receiver<ServerMessage>> {
        self.broadcasters.get(table_id).map(|b| b.value().subscribe())
    }

    pub fn remove_table(&self, table_id: &Uuid) {
        self.tables.remove(table_id);
        self.broadcasters.remove(table_id);
    }

    /// Load all active tables from database
    pub async fn initialize_from_db(&self) -> Result<(), crate::errors::AppError> {
        use crate::db::queries;
        let active_tables = queries::list_tables(&self.db).await?;
        for t in active_tables {
            if !self.tables.contains_key(&t.id) {
                self.create_table(
                    t.id,
                    t.created_by,
                    t.small_blind,
                    t.big_blind,
                    t.min_buy_in,
                    t.max_buy_in,
                    t.max_players as usize,
                );
            }
        }
        Ok(())
    }

    /// Lazily ensure a table is in memory if it exists in DB
    pub async fn ensure_table(&self, table_id: &Uuid) -> Result<Option<Arc<tokio::sync::Mutex<PokerTable>>>, crate::errors::AppError> {
        if let Some(table) = self.get_table(table_id) {
            return Ok(Some(table));
        }

        use crate::db::queries;
        if let Some(t) = queries::get_table_by_id(&self.db, *table_id).await? {
            self.create_table(
                t.id,
                t.created_by,
                t.small_blind,
                t.big_blind,
                t.min_buy_in,
                t.max_buy_in,
                t.max_players as usize,
            );
            return Ok(self.get_table(table_id));
        }

        Ok(None)
    }

    /// Periodic tick to check for timeouts on all tables
    pub async fn tick(&self) {
        for entry in self.tables.iter() {
            let table_id = *entry.key();
            let table_arc = entry.value().clone();
            let mut table = table_arc.lock().await;

            if let Some(messages) = table.check_timeouts() {
                if let Some(broadcaster) = self.get_broadcaster(&table_id) {
                    // Send all messages generated by the timeout action
                    for m in messages {
                        let _ = broadcaster.send(m);
                    }
                    // Always broadcast updated game state after an auto-fold
                    let _ = broadcaster.send(table.build_game_state_message());
                }
            }
        }
    }
}
